#!/usr/bin/env python3
"""Generate tb/smoke/cf_smoke_top.sv: the M0 smoke harness that instantiates all four upstream
IPs in one Verilator model. Ports are read from each IP's module header so the harness follows
submodule bumps; rerun after a bump (`make smoke-build` does). Every data/valid input is tied
low (idle bus), clk/rst_n are driven, and every output is folded into a parity word so nothing
is optimised away."""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# (instance, module, file, identifier -> expression used in widths)
IPS = [
    ("u_vortex", "vortex_soc", "third_party/vortex-v/rtl/soc/vortex_soc.sv", {}),
    ("u_mlacc", "mlacc_top", "third_party/mlacc-uvm/rtl/mlacc_top.sv",
     {"TAG_W": "mlacc_pkg::TAG_W", "XLEN": "mlacc_pkg::XLEN"}),
    ("u_nanoxl", "nanoxl_top", "third_party/nanoxl-accelerator/rtl/nanoxl_top.sv", {"AW": "32"}),
    ("u_spikemesh", "spikemesh_top", "third_party/spikemesh/rtl/top/spikemesh_top.sv", {}),
]
PORT = re.compile(r"^\s*(input|output)\s+logic\s*(\[[^\]]+\])?\s*(\w+)\s*,?")

def ports(path, module):
    text = re.sub(r"//[^\n]*", "", (ROOT / path).read_text())
    head = text[text.index(f"module {module}"):]
    head = head[:head.index(");")]
    out = []
    for line in head.splitlines():
        m = PORT.match(line)
        if m:
            out.append((m.group(1), m.group(2) or "", m.group(3)))
    if not out:
        sys.exit(f"no ports parsed for {module}")
    return out

def subst(rng, table):
    for k, v in table.items():
        rng = re.sub(rf"\b{k}\b", v, rng)
    return rng

def main():
    lines = ["// GENERATED by scripts/gen_smoke_top.py: do not edit.",
             "// M0 smoke harness: Vortex-V SoC, MLACC, NanoXL and SpikeMesh in one Verilator model.",
             "`default_nettype none",
             "module cf_smoke_top;",
             "  localparam int CYCLES = 2000;",
             "  logic clk = 1'b0, rst_n = 1'b0;",
             "  always #5 clk = ~clk;",
             "  logic [63:0] parity = '0;", ""]
    folds = []
    for inst, mod, path, table in IPS:
        ps = ports(path, mod)
        conns = []
        for d, rng, name in ps:
            if name in ("clk", "rst_n"):
                conns.append(f"    .{name}({name})")
                continue
            sig = f"{inst}_{name}"
            r = subst(rng, table)
            lines.append(f"  logic {r + ' ' if r else ''}{sig};")
            if d == "input":
                lines.append(f"  assign {sig} = '0;")
            else:
                folds.append(sig)
            conns.append(f"    .{name}({sig})")
        lines.append(f"  {mod} {inst} (\n" + ",\n".join(conns) + "\n  );\n")
    lines.append("  always_ff @(posedge clk) if (rst_n) parity <= parity ^ 64'({")
    lines.append("    " + ",\n    ".join(f"^{s}" for s in folds))
    lines.append("  });")
    lines += ["",
              "  initial begin",
              "    repeat (10) @(posedge clk);",
              "    rst_n = 1'b1;",
              "    repeat (CYCLES) @(posedge clk);",
              "    $display(\"smoke: %0d cycles, output parity %016h\", CYCLES, parity);",
              "    if ($isunknown(parity)) $display(\"*** SMOKE FAILED ***\");",
              "    else $display(\"*** SMOKE PASSED ***\");",
              "    $finish;",
              "  end",
              "endmodule",
              "`default_nettype wire", ""]
    (ROOT / "tb/smoke/cf_smoke_top.sv").write_text("\n".join(lines))

if __name__ == "__main__":
    main()
